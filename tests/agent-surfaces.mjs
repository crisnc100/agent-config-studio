import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { tempDir } from './fixtures/cleanup.mjs';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const home = fs.realpathSync(tempDir('acs-agent-surfaces-'));
const bin = path.join(home, 'bin'); fs.mkdirSync(bin);
fs.writeFileSync(path.join(bin, 'cmux'), `#!${process.execPath}\nimport(${JSON.stringify(path.join(root, 'tests/fixtures/agent-cmux.mjs'))});\n`, { mode: 0o755 });
const env = { ...process.env, HOME: home, PATH: `${bin}:${process.env.PATH}`, CMUX_SOCKET_PATH: 'fake', CMUX_WORKSPACE_ID: 'workspace:1' };
for (const key of ['CODEX_HOME', 'CLAUDE_CONFIG_DIR', 'GROK_HOME']) delete env[key];
const run = (args, extra = {}) => spawnSync(process.execPath, [path.join(root, 'bin/agent.mjs'), ...args], { env: { ...env, ...extra }, encoding: 'utf8', timeout: 10000 });
const json = r => { assert.equal(r.status, 0, r.stderr); return JSON.parse(r.stdout); };
const statePath = path.join(home, 'fake-cmux.json');
const state = () => JSON.parse(fs.readFileSync(statePath));
const mutate = fn => { const s = state(); fn(s); fs.writeFileSync(statePath, JSON.stringify(s)); };
const calls = verb => state().calls.filter(a => a.includes(verb));
const flag = (a, f) => a[a.indexOf(f) + 1];
// Every open is checked on its own: one new-surface in the caller's pane and workspace, without focus.
const open = (extra = {}) => {
  const before = fs.existsSync(statePath) ? state().calls.length : 0;
  const w = json(run(['open', 'sol', '--cwd', home, 'task', '--json'], extra));
  const placed = state().calls.slice(before).filter(a => a.includes('new-surface') || a.includes('new-pane'));
  assert.equal(placed.length, 1, JSON.stringify(placed));
  assert.deepEqual(['new-surface', '--pane', '--workspace', '--focus'].map(f => f === 'new-surface' ? placed[0].includes(f) : placed[0][placed[0].indexOf(f) + 1]), [true, 'pane:1', 'workspace:1', 'false'], JSON.stringify(placed[0]));
  return w;
};
const first = open();
const second = open();
const third = open();
for (const w of [first, second, third]) assert.equal(w.pane_ref, 'pane:1', "every worker opens as a tab in the caller's own pane");
assert.equal(calls('new-pane').length, 0, 'a worker never opens a pane');
assert.ok(calls('list-pane-surfaces').every(a => flag(a, '--pane') === 'pane:1' && flag(a, '--workspace') === 'workspace:1'), "only the caller's pane is looked up, to reselect its tab");
assert.equal(state().selected['pane:1'], 'surface:1', "the caller's own tab is selected again after every open");
const raced = run(['open', 'sol', '--cwd', home, 'task'], { FAKE_NEW_SURFACE_ERROR: 'not_found', FAKE_ERROR_STYLE: 'stderr' });
assert.equal(raced.status, 1, 'a caller pane that vanished is an error');
assert.equal(calls('new-pane').length, 0, 'a missing caller pane is never replaced by a new one');
const denied = run(['open', 'sol', '--cwd', home, 'task'], { FAKE_NEW_SURFACE_ERROR: 'permission_denied' });
assert.equal(denied.status, 1); assert.match(denied.stderr, /permission_denied/);
assert.equal(calls('new-pane').length, 0, 'non-missing errors must not create panes');
mutate(s => { s.workers[first.surface_ref].closed = true; });
const missing = run(['wait', first.id, '--timeout', '0', '--json']);
assert.equal(missing.status, 8, missing.stderr); assert.equal(JSON.parse(missing.stdout).state, 'closed');
assert.equal(JSON.parse(missing.stdout).closed, true);
const record = id => JSON.parse(fs.readFileSync(path.join(home, '.agent-config-studio/agents', `${id}.json`)));
assert.equal(record(first.id).status, 'closed');
assert.equal(run(['wait', first.id, '--timeout', '0']).stdout.trim(), 'closed');
assert.equal(run(['wait', first.id, '--timeout', '0']).status, 8);
json(run(['close', first.id, '--json']));
const explicit = open(); json(run(['close', explicit.id, '--json']));
assert.equal(run(['wait', explicit.id, '--timeout', '0']).status, 8);
mutate(s => { s.workers[third.surface_ref].closed = true; });
json(run(['close', third.id, '--json']));
assert.equal(record(third.id).status, 'closed', 'close is idempotent after manual surface removal');
const idle = open();
json(run(['wait', idle.id, '--timeout', '0', '--json']));
const idlePath = path.join(home, '.agent-config-studio/agents', `${idle.id}.json`);
const idleRecord = record(idle.id);
idleRecord.lastActivityAt = Date.now() - 31 * 60000;
idleRecord.finishedAt = idleRecord.lastActivityAt;
fs.writeFileSync(idlePath, JSON.stringify(idleRecord));
const expired = run(['wait', idle.id, '--timeout', '0', '--json']);
assert.equal(expired.status, 8, expired.stderr);
assert.equal(JSON.parse(expired.stdout).state, 'closed');
assert.equal(JSON.parse(expired.stdout).closed, true);
const moving = open({ FAKE_RUNNING: '1' });
const vanished = run(['wait', moving.id, '--timeout', '3', '--json'], { FAKE_REMOVE_AFTER_READ: '1', FAKE_ERROR_STYLE: 'stderr' });
assert.equal(vanished.status, 8, vanished.stderr); assert.equal(JSON.parse(vanished.stdout).state, 'closed');
assert.equal(record(moving.id).status, 'closed');
const offline = open({ FAKE_RUNNING: '1' });
const screenError = run(['wait', offline.id, '--timeout', '0'], { FAKE_READ_SCREEN_ERROR: 'permission_denied' });
assert.equal(screenError.status, 1); assert.match(screenError.stderr, /permission_denied/);
assert.notEqual(record(offline.id).status, 'closed', 'unrelated screen errors must not close a worker');
assert.equal(run(['wait', offline.id, '--timeout', '0'], { FAKE_OFFLINE: '1' }).status, 2, 'socket errors are not closure');
assert.notEqual(record(offline.id).status, 'closed');
console.log('agent tabs in the caller pane, no pane on errors, missing surfaces, closure exit 8 and unrelated errors passed');
