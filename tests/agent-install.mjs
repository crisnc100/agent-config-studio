import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { install as installAgent } from '../bin/agent-install.mjs';
import { tempDir } from './fixtures/cleanup.mjs';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const home = fs.realpathSync(tempDir('acs-agent-install-'));
const env = { ...process.env, HOME: home, ACS_NO_UPDATE: '1', ACS_NO_OPEN: '1' };
for (const key of ['CODEX_HOME', 'CLAUDE_CONFIG_DIR', 'GROK_HOME']) delete env[key];
const install = () => spawnSync('/bin/sh', [path.join(root, 'bin/acs'), 'install-model-id'], { env, encoding: 'utf8' });
const legacyAgent = path.join(home, '.local/bin/agent');
fs.mkdirSync(path.dirname(legacyAgent), { recursive: true });
fs.symlinkSync(path.join(home, '.grok/bin/agent'), legacyAgent);
const first = install();
assert.equal(first.status, 0, first.stderr);
const agent = path.join(home, '.local/bin/acs-agent');
const launcher = path.join(home, '.agent-config-studio/bin/acs-agent');
assert.equal(fs.readlinkSync(agent), launcher);
assert.equal(fs.readlinkSync(legacyAgent), path.join(home, '.grok/bin/agent'));
assert.ok(!fs.existsSync(path.join(home, '.agent-config-studio/bin/agent')));
assert.ok(fs.lstatSync(agent).isSymbolicLink());
const copied = path.join(home, '.agent-config-studio/resolver');
for (const file of ['bin/agent.mjs', 'bin/agent-install.mjs', 'lib/agent.js', 'lib/paths.js', 'lib/roots.js']) assert.equal(fs.readFileSync(path.join(copied, file), 'utf8'), fs.readFileSync(path.join(root, file), 'utf8'));
const r = spawnSync(agent, ['--help'], { env, encoding: 'utf8' });
assert.equal(r.status, 0, r.stderr);
assert.match(r.stdout, /usage: acs-agent open/);
assert.equal(spawnSync(agent, ['list'], { env: { ...env, CMUX_SOCKET_PATH: '' }, encoding: 'utf8' }).status, 2);
assert.equal(install().status, 0);
fs.unlinkSync(agent); fs.writeFileSync(agent, 'keep me');
const conflict = install();
assert.equal(conflict.status, 1);
assert.equal(fs.readFileSync(agent, 'utf8'), 'keep me');
assert.match(conflict.stderr, /not a symlink/);
assert.equal(fs.readlinkSync(legacyAgent), path.join(home, '.grok/bin/agent'));
for (const foreignLink of [true, false]) {
  const blockedHome = fs.realpathSync(tempDir('acs-agent-conflict-'));
  const studio = path.join(blockedHome, '.agent-config-studio');
  const blocked = path.join(blockedHome, '.local/bin/acs-agent');
  fs.mkdirSync(path.dirname(blocked), { recursive: true });
  const foreign = path.join(blockedHome, 'foreign');
  fs.writeFileSync(foreign, 'keep foreign target');
  if (foreignLink) fs.symlinkSync(foreign, blocked);
  else fs.writeFileSync(blocked, 'keep file');
  assert.throws(() => installAgent({ home: blockedHome, studio, resolver: path.join(studio, 'resolver') }), /acs-agent.*not replacing/);
  assert.ok(!fs.existsSync(studio));
  if (foreignLink) assert.equal(fs.readlinkSync(blocked), foreign);
  else assert.equal(fs.readFileSync(blocked, 'utf8'), 'keep file');
  assert.equal(fs.readFileSync(foreign, 'utf8'), 'keep foreign target');
}
console.log('agent install passed');
const fake = path.join(home, 'fake-bin');
fs.mkdirSync(fake);
const fixture = path.join(fake, 'fake-cmux.mjs');
fs.copyFileSync(path.join(root, 'tests/fixtures/agent-cmux.mjs'), fixture);
fs.writeFileSync(path.join(fake, 'cmux'), `#!${process.execPath}\nimport(${JSON.stringify(fixture)});\n`, { mode: 0o755 });
fs.unlinkSync(agent);
assert.equal(install().status, 0);
const installedEnv = { ...env, PATH: `${fake}:${env.PATH}`, CMUX_SOCKET_PATH: path.join(home, 'socket'), CMUX_WORKSPACE_ID: 'workspace:1' };
const opened = spawnSync(agent, ['open', 'sol', '--cwd', home, 'installed task'], { env: installedEnv, encoding: 'utf8' });
assert.equal(opened.status, 0, opened.stderr);
const waited = spawnSync(agent, ['wait', opened.stdout.trim(), '--timeout', '0'], { env: installedEnv, encoding: 'utf8' });
assert.equal(waited.status, 0, waited.stderr);
assert.equal(waited.stdout, 'done\n');
console.log('installed agent lifecycle passed');
