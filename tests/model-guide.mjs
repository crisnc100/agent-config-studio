    const fixtures = [
      ['an empty file', ''],
      ['no trailing newline', 'notes'],
      ['one trailing newline', 'notes\n'],
      ['two trailing newlines', 'notes\n\n'],
      ['three trailing newlines', 'notes\n\n\n'],
      ['CRLF, no trailing newline', 'a\r\nb'],
      ['CRLF, one trailing newline', 'a\r\nb\r\n'],
      ['CRLF, two trailing newlines', 'a\r\nb\r\n\r\n'],
      ['a BOM and unicode', '﻿# Héllo ✓\n'],
    ];
    for (const [what, orig] of fixtures) {
      const inst = planEdit(B(orig), 'install', body).bytes;
      const text = inst.toString('utf8');
      ok(`${what}: install keeps every original byte in front`, inst.subarray(0, B(orig).length).equals(B(orig)));
      const eol = orig.includes('\r\n') ? '\r\n' : '\n';
      const blockAt = text.indexOf('<!-- acs:model-guide');
      const gap = text.slice(B(orig).length, blockAt);
      ok(`${what}: exactly one blank line before the block (none for an empty file)`, orig === '' ? blockAt === 0 : text.slice(0, blockAt).endsWith(`${eol}${eol}`) && !text.slice(0, blockAt).endsWith(`${eol}${eol}${eol}`) || orig.endsWith(`${eol}${eol}${eol}`) && gap === '', JSON.stringify(gap));
      ok(`${what}: the block uses the file's line ending`, eol === '\r\n' ? !/[^\r]\n/.test(text.slice(blockAt)) : !text.slice(blockAt).includes('\r'));
      ok(`${what}: install → current`, inspect(text, body).status === 'current');
      const removed = planEdit(inst, 'remove', body).bytes;
      ok(`${what}: install → remove gives back the original bytes`, removed.equals(B(orig)), JSON.stringify(removed.toString()));
      const stale = planEdit(B(orig), 'install', body.replace('reads a diff', 'read a diff')).bytes;
      const upd = planEdit(stale, 'update', body).bytes;
      ok(`${what}: install → update → remove round-trips`, inspect(upd.toString(), body).status === 'current' && planEdit(upd, 'remove', body).bytes.equals(B(orig)));
    }
    const mid = `# Mine\n\nkeep this\n\n${renderBlock(body.replace('reads a diff', 'old'), 0)}\nafter the block\r\nand é more`;
    const upd = planEdit(B(mid), 'update', body).bytes.toString('utf8');
    const [pre, post] = [mid.slice(0, mid.indexOf('<!-- acs')), mid.slice(mid.indexOf('<!-- /acs:model-guide -->') + 25)];
